//! Extract only model-relevant fields from typed actions, without JSON.
use rustmage::{Action, Counters, Target, ObjectRef, Player, EntryChoiceValue, ManaCost,
    CastFace, LibraryDestination, PermanentType, Card, CombatDefender, ConvokeContribution,
    CounterKind, DamagePreventionKind, ForageRoute, LibraryPile, ManaValueParity,
    SearchDestination, ZoneReplacementKind, CreatureType};

#[derive(Clone, Debug)]
pub enum Value {
    Null, Bool(bool), Integer(i128), Mana([u32; 6]), Counters([u64; 60]), Target(Target),
    Object(ObjectRef), Player(Player), Name(String), Entry(EntryChoiceValue), Cost(ManaCost), Card(Card), Defender(CombatDefender),
    Permission(ObjectRef, PermanentType), Destination(SearchDestination), Replacement(ZoneReplacementKind),
}
pub trait Field { fn field(&self) -> Value; }
impl Field for bool { fn field(&self)->Value { Value::Bool(*self) } }
macro_rules! ints { ($($t:ty),*) => {$(impl Field for $t { fn field(&self)->Value { Value::Integer(*self as i128) } })*}; }
ints!(u8,u16,u32,u64,i128);
impl<T:Field> Field for Option<T> { fn field(&self)->Value { self.as_ref().map_or(Value::Null,Field::field) } }
impl Field for [u32;6] { fn field(&self)->Value {Value::Mana(*self)} }
impl Field for Counters { fn field(&self)->Value { let mut values=[0;60];
    values[..5].copy_from_slice(&[self.plus_one,self.minus_one,self.stun,self.loyalty,self.lore]);
    for (index,kind) in crate::entity::NAMED_COUNTERS.iter().enumerate(){ values[index+5]=self.get(*kind); }
    Value::Counters(values) } }
impl Field for Target { fn field(&self)->Value { Value::Target(*self) } }
impl Field for ObjectRef { fn field(&self)->Value { Value::Object(*self) } }
impl Field for Player { fn field(&self)->Value { Value::Player(*self) } }
impl Field for EntryChoiceValue { fn field(&self)->Value { Value::Entry(*self) } }
impl Field for ManaCost { fn field(&self)->Value { Value::Cost(*self) } }
macro_rules! names { ($($t:ty),*) => {$(impl Field for $t { fn field(&self)->Value { Value::Name(format!("{self:?}")) } })*}; }
names!(CastFace,LibraryDestination,PermanentType,ConvokeContribution,CounterKind,
       DamagePreventionKind,ForageRoute,LibraryPile,ManaValueParity);
impl Field for Card { fn field(&self)->Value {Value::Card(*self)} }
impl Field for CombatDefender { fn field(&self)->Value {Value::Defender(*self)} }
impl Field for SearchDestination { fn field(&self)->Value {Value::Destination(*self)} }
impl Field for ZoneReplacementKind { fn field(&self)->Value {Value::Replacement(*self)} }
impl Field for CreatureType { fn field(&self)->Value {Value::Name(self.name().to_string())} }
impl Field for (ObjectRef,PermanentType) { fn field(&self)->Value {Value::Permission(self.0,self.1)} }


pub struct ActionFields { pub kind: &'static str, pub fields: Vec<(&'static str,Value)> }
impl ActionFields {
    pub fn get(&self,key:&str)->Option<&Value> { self.fields.iter().find(|(k,_)|*k==key).map(|(_,v)|v) }
}
macro_rules! fields {($name:literal $(,$key:ident)* $(,)?) => { ActionFields { kind:$name, fields:vec![$((stringify!($key),$key.field())),*] } };}

